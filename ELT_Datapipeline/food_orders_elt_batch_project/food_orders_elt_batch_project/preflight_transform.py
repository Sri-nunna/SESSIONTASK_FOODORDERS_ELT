"""Run the Pandas extraction/transform/validation path without MySQL.

This is a useful local preflight. It does NOT replace running elt_batch_pipeline.py
against MySQL; the full execution report is generated by the full pipeline.
"""
import pandas as pd
from config import DATA_FILE, BATCH_SIZE, SOURCE_COLUMNS, REPORT_DIR
from transform import transform_batch
from validate import validate_frame

def run_preflight():
    seen_fingerprints, seen_order_ids = set(), set()
    valid_frames, rejected_frames = [], []
    total_rows = batch_count = 0

    for batch_count, raw_batch in enumerate(
        pd.read_csv(DATA_FILE, dtype=str, keep_default_na=False, chunksize=BATCH_SIZE),
        start=1
    ):
        raw_batch = raw_batch[SOURCE_COLUMNS].copy()
        raw_batch.insert(0, "source_row_number",
                         range(total_rows + 1, total_rows + len(raw_batch) + 1))
        total_rows += len(raw_batch)
        valid, rejected = transform_batch(raw_batch, seen_fingerprints, seen_order_ids)
        if not valid.empty:
            valid_frames.append(valid)
        if not rejected.empty:
            rejected_frames.append(rejected)
        print(f"Preflight batch {batch_count}: input={len(raw_batch)}, "
              f"valid={len(valid)}, rejected={len(rejected)}")

    valid_all = pd.concat(valid_frames, ignore_index=True) if valid_frames else pd.DataFrame()
    rejected_all = pd.concat(rejected_frames, ignore_index=True) if rejected_frames else pd.DataFrame()
    checks = validate_frame(valid_all) if not valid_all.empty else {"non_empty_valid_dataset": False}

    rejected_path = REPORT_DIR / "preflight_rejected_records.csv"
    report_path = REPORT_DIR / "source_preflight_report.json"
    rejected_all.to_csv(rejected_path, index=False)
    report = {
        "report_type": "Pandas preflight only - MySQL not executed",
        "source_file": DATA_FILE.name,
        "source_records": total_rows,
        "batch_size": BATCH_SIZE,
        "source_batches": batch_count,
        "valid_transformed_records": len(valid_all),
        "rejected_records": len(rejected_all),
        "rejection_reasons": rejected_all["rejection_reason"].value_counts().to_dict()
            if not rejected_all.empty else {},
        "missing_values_in_valid_output": valid_all.isna().sum().to_dict(),
        "validation_checks": checks,
        "validation_status": "PASS" if all(checks.values()) else "FAIL",
        "rejected_records_file": "reports/preflight_rejected_records.csv"
    }
    import json
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=4, default=str)
    print(f"Preflight report saved: {report_path}")
    return report

if __name__ == "__main__":
    run_preflight()
